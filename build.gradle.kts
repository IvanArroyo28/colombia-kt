// Downloads DIVIPOLA from datos.gov.co (DANE, CC BY-SA 4.0) and regenerates the data files.
// Run it when DANE publishes an update:  ./gradlew updateDivipola
tasks.register("updateDivipola") {
    group = "data"
    description = "Downloads DIVIPOLA (DANE) from datos.gov.co and regenerates the resource files."
    val outputDir = layout.projectDirectory.dir("src/main/resources/io/github/ivanarroyo28/colombia/divipola")

    doLast {
        val url = URI("https://www.datos.gov.co/resource/gdxc-w37w.json?\$limit=5000&\$order=cod_mpio").toURL()
        @Suppress("UNCHECKED_CAST")
        val rows = JsonSlurper().parse(url, "UTF-8") as List<Map<String, String>>
        check(rows.size > 1000) { "Unexpected DIVIPOLA size: ${rows.size}" }

        val types = mapOf("Municipio" to "M", "Isla" to "I", "Área no municipalizada" to "A")
        val header = "# DIVIPOLA - DANE (datos.gov.co, dataset gdxc-w37w). License: CC BY-SA 4.0. Generated by ./gradlew updateDivipola\n"
        val dir = outputDir.asFile.apply { mkdirs() }

        val municipalities = rows.joinToString("\n", prefix = header, postfix = "\n") { row ->
            val type = types[row["tipo_municipio"]] ?: error("Unknown type: ${row["tipo_municipio"]}")
            listOf(row["cod_mpio"], row["nom_mpio"], type, row["latitud"], row["longitud"]).joinToString("\t")
        }
        val departments = rows.map { "${it["cod_dpto"]}\t${it["dpto"]}" }
            .distinct()
            .joinToString("\n", prefix = header, postfix = "\n")

        dir.resolve("municipios.tsv").writeText(municipalities, Charsets.UTF_8)
        dir.resolve("departamentos.tsv").writeText(departments, Charsets.UTF_8)
        println("DIVIPOLA updated: ${rows.size} municipalities and areas")
    }
}

